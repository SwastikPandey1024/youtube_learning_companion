# ── Factory ───────────────────────────────────────────────────────────────────


def create_llm_client(
    provider_name: str | None = None,
    api_key: str | None = None,
    base_url: str | None = None,
    model: str | None = None,
    timeout_seconds: float | None = None,
) -> BaseLLMClient:
    """Factory creating configured BaseLLMClient instances."""
    from youtube_learning_companion.config import get_settings

    settings = get_settings()
    prov = (provider_name or settings.llm_provider).strip().lower()

    if prov == "mock":
        return MockLLMClient()

    if prov in ("openai", "ollama", "vllm", "custom"):
        key = api_key if api_key is not None else settings.llm_api_key
        url = base_url or settings.llm_api_base_url
        mdl = model or settings.llm_model
        tout = timeout_seconds or settings.llm_timeout_seconds
        return OpenAILLMClient(
            api_key=key,
            base_url=url,
            model=mdl,
            timeout_seconds=tout,
            max_retries=settings.llm_max_retries,
            provider_name=prov,
        )

    raise ValueError(f"Unsupported LLM provider '{prov}'. Supported: 'openai', 'ollama', 'mock'.")
